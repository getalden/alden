/**
 * Builds standalone `alden` executables with Bun, which need no Node: `pnpm build:binary [--target <t>...]`.
 *
 * Run `pnpm build` first: the binary carries the built UI and the grammars inside it. They're inlined into a
 * generated module (build/binary/), and an entry point registers them before the CLI starts, so the code finds them
 * the same way on every runtime. Targets default to the host; `--all` builds macOS (arm64, x64), Linux (x64, arm64)
 * and Windows (x64) into dist-bin/.
 *
 * The native keychain module is embedded by Bun for each target, which needs that platform's @napi-rs/keyring
 * package installed (see supportedArchitectures in pnpm-workspace.yaml).
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const OUT = join(ROOT, "build/binary");
const BIN = join(ROOT, "dist-bin");
const require = createRequire(import.meta.url);

const ALL = ["darwin-arm64", "darwin-x64", "linux-x64", "linux-arm64", "windows-x64"];
const host = `${process.platform === "win32" ? "windows" : process.platform}-${process.arch}`;
const args = process.argv.slice(2);
const targets = args.includes("--all")
  ? ALL
  : args.flatMap((a, i) => (args[i - 1] === "--target" ? [a] : [])).concat(args.includes("--target") ? [] : [host]);

const uiDir = join(ROOT, "packages/ui/dist");
const grammarsDir = join(ROOT, "packages/cli/dist/grammars");
for (const dir of [uiDir, grammarsDir]) {
  if (!existsSync(dir)) throw new Error(`${relative(ROOT, dir)} is missing: run \`pnpm build\` first.`);
}

function walk(dir: string, base = dir): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path, base) : [relative(base, path).split("\\").join("/")];
  });
}

// Everything the binary would otherwise read from disk, keyed the way core's embeddedFile() asks for it.
const files: [string, string][] = [
  ...walk(uiDir).map((p) => [`ui/${p}`, join(uiDir, p)] as [string, string]),
  ...walk(grammarsDir).map((p) => [`grammars/${p}`, join(grammarsDir, p)] as [string, string]),
  [
    "grammars/web-tree-sitter.wasm",
    require.resolve("web-tree-sitter/web-tree-sitter.wasm", { paths: [join(ROOT, "packages/core")] }),
  ],
];

mkdirSync(OUT, { recursive: true });
writeFileSync(
  join(OUT, "embedded.ts"),
  `// Generated by scripts/build-binary.ts. Do not edit.\nexport const EMBEDDED: [string, string][] = ${JSON.stringify(
    files.map(([key, path]) => [key, readFileSync(path).toString("base64")]),
  )};\n`,
);
writeFileSync(
  join(OUT, "entry.ts"),
  `import { registerEmbeddedFiles } from "../../packages/core/src/index.js";
import { EMBEDDED } from "./embedded.js";

registerEmbeddedFiles(EMBEDDED.map(([path, base64]) => [path, Buffer.from(base64, "base64")]));
await import("../../packages/cli/src/index.js");
`,
);
const size = files.reduce((n, [, path]) => n + statSync(path).size, 0);
console.log(`Embedded ${files.length} files (${(size / 1024 / 1024).toFixed(1)} MB).`);

mkdirSync(BIN, { recursive: true });
// The bun package's own executable (bin/bun.exe on every platform), not node_modules/.bin/bun: on Windows that's
// only a .cmd shim, which can't be spawned directly.
const bun = join(dirname(require.resolve("bun/package.json")), "bin", "bun.exe");
for (const target of targets) {
  const outfile = join(BIN, `alden-${target}${target.startsWith("windows") ? ".exe" : ""}`);
  execFileSync(
    bun,
    [
      "build",
      join(OUT, "entry.ts"),
      "--compile",
      "--minify",
      `--target=bun-${target}`,
      `--outfile=${outfile}`,
      // Cloud-platform SDKs load only when configured; the binary says to use npm for those.
      "--external=@anthropic-ai/bedrock-sdk",
      "--external=@anthropic-ai/vertex-sdk",
      "--external=@anthropic-ai/foundry-sdk",
    ],
    { stdio: "inherit", cwd: ROOT },
  );
  console.log(`${relative(ROOT, outfile)}: ${(statSync(outfile).size / 1024 / 1024).toFixed(1)} MB`);
}
