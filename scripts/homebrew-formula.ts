/**
 * Writes the Homebrew formula for a release: `pnpm homebrew:formula <version> <checksums file>`.
 *
 * The checksums file is `shasum -a 256` output for the release archives (alden-<version>-<target>.tar.gz). The
 * formula installs the standalone binary for the machine, so Homebrew users need no Node. The release workflow
 * commits the result to getalden/homebrew-tap as Formula/alden.rb.
 */
import { readFileSync } from "node:fs";

const [version, checksumsFile] = process.argv.slice(2);
if (!version || !checksumsFile) throw new Error("Usage: pnpm homebrew:formula <version> <checksums file>");

const sums = new Map(
  readFileSync(checksumsFile, "utf8")
    .split("\n")
    .flatMap((line) => {
      const [sum, file] = line.trim().split(/\s+\*?/);
      return sum && file ? [[file, sum] as const] : [];
    }),
);
const asset = (target: string) => {
  const file = `alden-${version}-${target}.tar.gz`;
  const sha = sums.get(file);
  if (!sha) throw new Error(`No checksum for ${file} in ${checksumsFile}.`);
  return `      url "https://github.com/getalden/homebrew-tap/releases/download/v${version}/${file}"
      sha256 "${sha}"`;
};

process.stdout.write(`# Generated by scripts/homebrew-formula.ts in getalden/alden for v${version}. Do not edit by hand.
class Alden < Formula
  desc "Code review companion that triages your PR queue and briefs you on each PR"
  homepage "https://getalden.dev"
  version "${version}"
  license "Apache-2.0"

  on_macos do
    on_arm do
${asset("darwin-arm64")}
    end
    on_intel do
${asset("darwin-x64")}
    end
  end

  on_linux do
    on_arm do
${asset("linux-arm64")}
    end
    on_intel do
${asset("linux-x64")}
    end
  end

  def install
    bin.install "alden"
  end

  test do
    assert_equal "${version}", shell_output("ALDEN_NO_UPDATE_CHECK=1 #{bin}/alden --version").strip
  end
end
`);
