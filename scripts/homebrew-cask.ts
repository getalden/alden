/**
 * Writes the Homebrew cask for the desktop app: `pnpm homebrew:cask <version> <checksums file>`.
 *
 * The checksums file is the release's SHA256SUMS, which lists Alden-<version>-universal.dmg. The release workflow
 * commits the result to getalden/homebrew-tap as Casks/alden-desktop.rb, so `brew install --cask
 * getalden/tap/alden-desktop` installs Alden.app. The app carries its own `alden`, which the cask links into Homebrew's
 * bin, so installing the app gives you the command too; if the `alden` formula is already there, its link is kept.
 */
import { readFileSync } from "node:fs";

const [version, checksumsFile] = process.argv.slice(2);
if (!version || !checksumsFile) throw new Error("Usage: pnpm homebrew:cask <version> <checksums file>");

const file = `Alden-${version}-universal.dmg`;
const sha = readFileSync(checksumsFile, "utf8")
  .split("\n")
  .map((line) => line.trim().split(/\s+\*?/))
  .find(([, name]) => name === file)?.[0];
if (!sha) throw new Error(`No checksum for ${file} in ${checksumsFile}.`);

process.stdout.write(`# Generated by scripts/homebrew-cask.ts in getalden/alden for v${version}. Do not edit by hand.
cask "alden-desktop" do
  version "${version}"
  sha256 "${sha}"

  url "https://github.com/getalden/homebrew-tap/releases/download/v#{version}/Alden-#{version}-universal.dmg"
  name "Alden"
  desc "Code review companion in the menu bar"
  homepage "https://getalden.dev/"

  depends_on macos: ">= :monterey"

  app "Alden.app"

  # The app carries the alden command: link it into Homebrew's bin (already on your PATH), unless the alden formula
  # put one there first.
  postflight do
    command = "#{HOMEBREW_PREFIX}/bin/alden"
    unless File.exist?(command) || File.symlink?(command)
      File.symlink("#{appdir}/Alden.app/Contents/MacOS/alden", command)
    end
  end

  uninstall_postflight do
    command = "#{HOMEBREW_PREFIX}/bin/alden"
    if File.symlink?(command) && File.readlink(command).end_with?("Alden.app/Contents/MacOS/alden")
      File.delete(command)
    end
  end

  # ~/.alden is shared with the alden command line tool, so it stays.
  zap trash: [
    "~/Library/Application Support/dev.getalden.desktop",
    "~/Library/Caches/dev.getalden.desktop",
    "~/Library/Preferences/dev.getalden.desktop.plist",
    "~/Library/Saved Application State/dev.getalden.desktop.savedState",
    "~/Library/WebKit/dev.getalden.desktop",
  ]
end
`);
